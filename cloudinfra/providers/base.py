"""The CloudProvider interface: the primitives every adapter implements. Nothing above this module names a cloud.

The orchestrator owns the lifecycle (order, state, cleanup on failure, destroy in reverse) and calls these primitives, so
an adapter implements creation, reading, change and deletion of each resource kind and gets the lifecycle for free.
"""
from abc import ABC, abstractmethod
from collections.abc import Callable
from dataclasses import dataclass, field

from ..models.errors import ErrorCode, InfrastructureError
from ..models.request import (
    RESOURCE_KINDS,
    CacheRequest,
    ClusterRequest,
    ComputeRequest,
    DatabaseRequest,
    InfrastructureRequest,
    JobRequest,
    LoadBalancerRequest,
    NetworkRequest,
    QueueRequest,
    SecretRequest,
    ServiceRequest,
    StorageRequest,
)
from ..models.resources import (
    CacheResource,
    ClusterResource,
    ComputeResource,
    ConnectInfo,
    DatabaseResource,
    FirewallRule,
    JobResource,
    LoadBalancerResource,
    NetworkResource,
    QueueResource,
    ResourceStatus,
    SecretResource,
    ServiceResource,
    StorageResource,
)
from ..models.response import CostEstimate, Health, PlannedResource, Usage


@dataclass(frozen=True)
class Problem:
    code: ErrorCode
    message: str
    field: str | None = None


@dataclass
class ProvisionContext:
    """What every creation carries: the request it belongs to, who asked, the labels every resource gets, where."""
    request_id: str
    name: str
    region: str
    zone: str | None
    owner: str | None = None
    labels: dict[str, str] = field(default_factory=dict)
    # Generated by the orchestrator when the request has a database, handed to the adapter and written to the request's secret, never kept.
    database_password: str | None = field(default=None, repr=False)
    # Set by the orchestrator while it provisions; see accepted().
    on_accepted: Callable | None = field(default=None, repr=False, compare=False)

    def accepted(self, resource) -> None:
        """An adapter calls this as soon as the provider has accepted a create, before it waits for the work to finish,
        with the resource as far as it will exist (its provider id and every part a delete must find). The orchestrator
        records it, so that a failure while waiting, or a restart, still deletes it. A delete of a part never made finds
        nothing and passes. Outside provisioning it does nothing."""
        if self.on_accepted is not None:
            self.on_accepted(resource)


class CloudProvider(ABC):
    name: str = "abstract"
    # The kinds this adapter implements; a request for another is refused with UNSUPPORTED_RESOURCE_KIND before any call.
    supported_kinds: tuple[str, ...] = RESOURCE_KINDS
    # Optional capabilities; an adapter lists the kinds it can stop and start, and grant access on.
    stoppable_kinds: tuple[str, ...] = ()
    grantable_kinds: tuple[str, ...] = ()

    # ---- knowledge: no network call
    @abstractmethod
    def regions(self) -> list[str]:
        """The regions this adapter can serve (before the operator's allow list)."""

    @abstractmethod
    def zones(self, region: str) -> list[str]:
        """The zones of a region; the first is the default."""

    @abstractmethod
    def validate(self, request: InfrastructureRequest) -> list[Problem]:
        """Provider-specific shape checks (a machine shape the provider has no type for, a database version it does not offer)."""

    @abstractmethod
    def plan(self, request: InfrastructureRequest, ctx: ProvisionContext) -> list[PlannedResource]:
        """The provider resources a request becomes, in creation order, named and shaped; pure, deterministic."""

    @abstractmethod
    def estimate_cost(self, planned: list[PlannedResource]) -> CostEstimate:
        """Monthly cost of a plan from the provider's list prices; an estimate, never a bill."""

    # ---- best effort, may be empty
    def quota(self, region: str) -> dict[str, dict]:
        """Quota headroom the provider reports for a region ({metric: {limit, usage}}); {} when it cannot be read."""
        return {}

    # ---- network
    @abstractmethod
    def create_network(self, spec: NetworkRequest, planned: PlannedResource, ctx: ProvisionContext) -> NetworkResource: ...

    @abstractmethod
    def configure_firewall(self, network: NetworkResource, ports: list[int], sources: list[str], ctx: ProvisionContext) -> FirewallRule: ...

    @abstractmethod
    def get_network(self, resource: NetworkResource) -> NetworkResource: ...

    @abstractmethod
    def delete_network(self, resource: NetworkResource, ctx: ProvisionContext) -> None: ...

    # ---- storage
    @abstractmethod
    def create_storage(self, spec: StorageRequest, planned: PlannedResource, ctx: ProvisionContext) -> StorageResource: ...

    @abstractmethod
    def attach_storage(self, storage: StorageResource, compute: ComputeResource, ctx: ProvisionContext) -> StorageResource: ...

    @abstractmethod
    def get_storage(self, resource: StorageResource) -> StorageResource: ...

    @abstractmethod
    def delete_storage(self, resource: StorageResource, ctx: ProvisionContext) -> None: ...

    # ---- compute
    @abstractmethod
    def create_compute(self, spec: ComputeRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> ComputeResource: ...

    @abstractmethod
    def get_compute(self, resource: ComputeResource) -> ComputeResource: ...

    @abstractmethod
    def list_compute(self, labels: dict[str, str]) -> list[ComputeResource]:
        """Every instance in the project that carries these labels, as the provider sees them now."""

    @abstractmethod
    def resize_compute(self, resource: ComputeResource, cpu: int, memory_gb: int, ctx: ProvisionContext) -> ComputeResource: ...

    @abstractmethod
    def delete_compute(self, resource: ComputeResource, ctx: ProvisionContext) -> None: ...

    # ---- database
    def prepare_network_for_database(self, network: NetworkResource, ctx: ProvisionContext) -> NetworkResource:
        """Whatever a network needs before a private database can join it (Google: a reserved range and a service peering);
        returns the network as it is afterwards. The default has nothing to do."""
        return network

    @abstractmethod
    def create_database(self, spec: DatabaseRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> tuple[DatabaseResource, str | None]:
        """The resource and the generated password of its user, returned once and never kept."""

    @abstractmethod
    def get_database(self, resource: DatabaseResource) -> DatabaseResource: ...

    @abstractmethod
    def delete_database(self, resource: DatabaseResource, ctx: ProvisionContext) -> None: ...

    # ---- cache
    @abstractmethod
    def create_cache(self, spec: CacheRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> CacheResource: ...

    @abstractmethod
    def get_cache(self, resource: CacheResource) -> CacheResource: ...

    @abstractmethod
    def delete_cache(self, resource: CacheResource, ctx: ProvisionContext) -> None: ...

    # ---- queue
    @abstractmethod
    def create_queue(self, spec: QueueRequest, planned: PlannedResource, ctx: ProvisionContext) -> QueueResource: ...

    @abstractmethod
    def get_queue(self, resource: QueueResource) -> QueueResource: ...

    @abstractmethod
    def delete_queue(self, resource: QueueResource, ctx: ProvisionContext) -> None: ...

    # ---- secret
    @abstractmethod
    def create_secret(self, spec: SecretRequest, planned: PlannedResource, ctx: ProvisionContext) -> SecretResource: ...

    @abstractmethod
    def get_secret(self, resource: SecretResource) -> SecretResource: ...

    @abstractmethod
    def delete_secret(self, resource: SecretResource, ctx: ProvisionContext) -> None: ...

    # ---- cluster
    @abstractmethod
    def create_cluster(self, spec: ClusterRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> ClusterResource: ...

    @abstractmethod
    def get_cluster(self, resource: ClusterResource) -> ClusterResource: ...

    @abstractmethod
    def delete_cluster(self, resource: ClusterResource, ctx: ProvisionContext) -> None: ...

    # ---- service (a managed container service)
    @abstractmethod
    def create_service(self, spec: ServiceRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None,
                       secrets: list[SecretResource]) -> ServiceResource: ...

    @abstractmethod
    def get_service(self, resource: ServiceResource) -> ServiceResource: ...

    @abstractmethod
    def delete_service(self, resource: ServiceResource, ctx: ProvisionContext) -> None: ...

    # ---- job (a managed job that runs to completion)
    @abstractmethod
    def create_job(self, spec: JobRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None,
                   secrets: list[SecretResource]) -> JobResource: ...

    @abstractmethod
    def get_job(self, resource: JobResource) -> JobResource: ...

    @abstractmethod
    def delete_job(self, resource: JobResource, ctx: ProvisionContext) -> None: ...

    # ---- load balancer
    @abstractmethod
    def create_load_balancer(self, spec: LoadBalancerRequest, planned: PlannedResource, ctx: ProvisionContext, backends: list[ComputeResource],
                             network: NetworkResource | None) -> LoadBalancerResource: ...

    @abstractmethod
    def get_load_balancer(self, resource: LoadBalancerResource) -> LoadBalancerResource: ...

    @abstractmethod
    def delete_load_balancer(self, resource: LoadBalancerResource, ctx: ProvisionContext) -> None: ...

    # ---- reading and deleting any resource
    def refresh(self, resource):
        """The resource as the provider sees it now, by kind."""
        return getattr(self, f"get_{resource.kind.value}")(resource)

    def delete(self, resource, ctx: ProvisionContext) -> None:
        getattr(self, f"delete_{resource.kind.value}")(resource, ctx)

    # ---- optional capabilities, each refused with a structured error until an adapter implements it
    def _unsupported(self, what: str, resource=None):
        kind = f" a {resource.kind.value}" if resource is not None else ""
        raise InfrastructureError(ErrorCode.UNSUPPORTED_RESOURCE_KIND, f"The {self.name} adapter cannot {what}{kind}", {"provider": self.name})

    def stop(self, resource, ctx: ProvisionContext):
        """Stop a resource that can stop, returning it as the provider sees it afterwards."""
        if resource.kind.value not in self.stoppable_kinds:
            self._unsupported("stop", resource)
        return getattr(self, f"stop_{resource.kind.value}")(resource, ctx)

    def start(self, resource, ctx: ProvisionContext):
        if resource.kind.value not in self.stoppable_kinds:
            self._unsupported("start", resource)
        return getattr(self, f"start_{resource.kind.value}")(resource, ctx)

    def takes_grants(self, kind: str, storage_type: str | None = None) -> bool:
        """Whether a resource of this kind (for storage, of this type: a bucket or a disk) has an access policy of its own."""
        return kind in self.grantable_kinds

    def resize_problem(self, resource: ComputeResource, cpu: int, memory_gb: int) -> Problem | None:
        """Why a machine cannot take a new shape (a machine with GPUs keeps their family), checked before any provider call;
        None when it can."""
        return None

    def boot_disk_gb(self, group: ComputeRequest) -> int:
        """The boot disk a compute group's machines get, which the adapter's software may make larger than asked."""
        return group.boot_disk_gb

    def estimate_resources(self, resources: list) -> CostEstimate:
        """What resources cost a month as they exist now (after a resize, whatever profile they came from), from list prices."""
        self._unsupported("price existing resources")

    def grant(self, resource, member: str, level: str, ctx: ProvisionContext) -> list[str]:
        """Grant a member access on one resource this service created, through the resource's own access policy; return
        the roles granted. Never a project-wide grant."""
        self._unsupported("grant access on", resource)

    def revoke(self, resource, member: str, ctx: ProvisionContext) -> None:
        self._unsupported("revoke access on", resource)

    def put_secret_value(self, resource: SecretResource, value: str, ctx: ProvisionContext) -> SecretResource:
        """Write a value the service generated as a new version; the value is never returned or logged."""
        self._unsupported("write a secret value to", resource)

    def read_cache_auth(self, resource: CacheResource) -> str:
        """The cache's own AUTH string, to be copied into a secret the request owns."""
        self._unsupported("read the AUTH string of", resource)

    def connect_info(self, resource, resources: list) -> ConnectInfo | None:
        """How to reach a resource, given the other resources of its request; None when there is nothing to say."""
        return None

    def busy_cores(self, resource: ComputeResource, minutes: int) -> float | None:
        """The busiest CPU sample of a machine in the last minutes, in cores; None when nothing was recorded."""
        return None

    def profile_infos(self) -> list[dict]:
        """The software profiles this adapter offers: name, description, accelerator rule."""
        return []

    def resource_status(self, resource) -> ResourceStatus:
        return self.refresh(resource).status

    @abstractmethod
    def resource_health(self, resource) -> Health: ...

    @abstractmethod
    def resource_usage(self, resource, minutes: int) -> Usage: ...
