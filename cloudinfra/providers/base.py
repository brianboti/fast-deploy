"""The CloudProvider interface: the primitives every adapter implements. Nothing above this module names a cloud.

The orchestrator owns the lifecycle (order, state, cleanup on failure, destroy in reverse) and calls these primitives, so
an adapter implements creation, reading, change and deletion of each resource kind and gets the lifecycle for free.
"""
from abc import ABC, abstractmethod
from dataclasses import dataclass, field

from ..models.errors import ErrorCode
from ..models.request import (
    RESOURCE_KINDS,
    CacheRequest,
    ClusterRequest,
    ComputeRequest,
    DatabaseRequest,
    InfrastructureRequest,
    LoadBalancerRequest,
    NetworkRequest,
    QueueRequest,
    SecretRequest,
    StorageRequest,
)
from ..models.resources import (
    CacheResource,
    ClusterResource,
    ComputeResource,
    DatabaseResource,
    FirewallRule,
    LoadBalancerResource,
    NetworkResource,
    QueueResource,
    ResourceStatus,
    SecretResource,
    StorageResource,
)
from ..models.response import CostEstimate, Health, PlannedResource, Usage


@dataclass(frozen=True)
class Problem:
    code: ErrorCode
    message: str
    field: str | None = None


@dataclass
class ProvisionContext:
    """What every creation carries: the request it belongs to, who asked, the labels every resource gets, where."""
    request_id: str
    name: str
    region: str
    zone: str | None
    owner: str | None = None
    labels: dict[str, str] = field(default_factory=dict)
    # Generated by the orchestrator when the request has a database, handed to the adapter, returned once to the caller, never kept.
    database_password: str | None = field(default=None, repr=False)


class CloudProvider(ABC):
    name: str = "abstract"
    # The kinds this adapter implements; a request for another is refused with UNSUPPORTED_RESOURCE_KIND before any call.
    supported_kinds: tuple[str, ...] = RESOURCE_KINDS

    # ---- knowledge: no network call
    @abstractmethod
    def regions(self) -> list[str]:
        """The regions this adapter can serve (before the operator's allow list)."""

    @abstractmethod
    def zones(self, region: str) -> list[str]:
        """The zones of a region; the first is the default."""

    @abstractmethod
    def validate(self, request: InfrastructureRequest) -> list[Problem]:
        """Provider-specific shape checks (a machine shape the provider has no type for, a database version it does not offer)."""

    @abstractmethod
    def plan(self, request: InfrastructureRequest, ctx: ProvisionContext) -> list[PlannedResource]:
        """The provider resources a request becomes, in creation order, named and shaped; pure, deterministic."""

    @abstractmethod
    def estimate_cost(self, planned: list[PlannedResource]) -> CostEstimate:
        """Monthly cost of a plan from the provider's list prices; an estimate, never a bill."""

    # ---- best effort, may be empty
    def quota(self, region: str) -> dict[str, dict]:
        """Quota headroom the provider reports for a region ({metric: {limit, usage}}); {} when it cannot be read."""
        return {}

    # ---- network
    @abstractmethod
    def create_network(self, spec: NetworkRequest, planned: PlannedResource, ctx: ProvisionContext) -> NetworkResource: ...

    @abstractmethod
    def configure_firewall(self, network: NetworkResource, ports: list[int], sources: list[str], ctx: ProvisionContext) -> FirewallRule: ...

    @abstractmethod
    def get_network(self, resource: NetworkResource) -> NetworkResource: ...

    @abstractmethod
    def delete_network(self, resource: NetworkResource, ctx: ProvisionContext) -> None: ...

    # ---- storage
    @abstractmethod
    def create_storage(self, spec: StorageRequest, planned: PlannedResource, ctx: ProvisionContext) -> StorageResource: ...

    @abstractmethod
    def attach_storage(self, storage: StorageResource, compute: ComputeResource, ctx: ProvisionContext) -> StorageResource: ...

    @abstractmethod
    def get_storage(self, resource: StorageResource) -> StorageResource: ...

    @abstractmethod
    def delete_storage(self, resource: StorageResource, ctx: ProvisionContext) -> None: ...

    # ---- compute
    @abstractmethod
    def create_compute(self, spec: ComputeRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> ComputeResource: ...

    @abstractmethod
    def get_compute(self, resource: ComputeResource) -> ComputeResource: ...

    @abstractmethod
    def list_compute(self, labels: dict[str, str]) -> list[ComputeResource]:
        """Every instance in the project that carries these labels, as the provider sees them now."""

    @abstractmethod
    def resize_compute(self, resource: ComputeResource, cpu: int, memory_gb: int, ctx: ProvisionContext) -> ComputeResource: ...

    @abstractmethod
    def delete_compute(self, resource: ComputeResource, ctx: ProvisionContext) -> None: ...

    # ---- database
    def prepare_network_for_database(self, network: NetworkResource, ctx: ProvisionContext) -> NetworkResource:
        """Whatever a network needs before a private database can join it (Google: a reserved range and a service peering);
        returns the network as it is afterwards. The default has nothing to do."""
        return network

    @abstractmethod
    def create_database(self, spec: DatabaseRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> tuple[DatabaseResource, str | None]:
        """The resource and the generated password of its user, returned once and never kept."""

    @abstractmethod
    def get_database(self, resource: DatabaseResource) -> DatabaseResource: ...

    @abstractmethod
    def delete_database(self, resource: DatabaseResource, ctx: ProvisionContext) -> None: ...

    # ---- cache
    @abstractmethod
    def create_cache(self, spec: CacheRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> CacheResource: ...

    @abstractmethod
    def get_cache(self, resource: CacheResource) -> CacheResource: ...

    @abstractmethod
    def delete_cache(self, resource: CacheResource, ctx: ProvisionContext) -> None: ...

    # ---- queue
    @abstractmethod
    def create_queue(self, spec: QueueRequest, planned: PlannedResource, ctx: ProvisionContext) -> QueueResource: ...

    @abstractmethod
    def get_queue(self, resource: QueueResource) -> QueueResource: ...

    @abstractmethod
    def delete_queue(self, resource: QueueResource, ctx: ProvisionContext) -> None: ...

    # ---- secret
    @abstractmethod
    def create_secret(self, spec: SecretRequest, planned: PlannedResource, ctx: ProvisionContext) -> SecretResource: ...

    @abstractmethod
    def get_secret(self, resource: SecretResource) -> SecretResource: ...

    @abstractmethod
    def delete_secret(self, resource: SecretResource, ctx: ProvisionContext) -> None: ...

    # ---- cluster
    @abstractmethod
    def create_cluster(self, spec: ClusterRequest, planned: PlannedResource, ctx: ProvisionContext, network: NetworkResource | None) -> ClusterResource: ...

    @abstractmethod
    def get_cluster(self, resource: ClusterResource) -> ClusterResource: ...

    @abstractmethod
    def delete_cluster(self, resource: ClusterResource, ctx: ProvisionContext) -> None: ...

    # ---- load balancer
    @abstractmethod
    def create_load_balancer(self, spec: LoadBalancerRequest, planned: PlannedResource, ctx: ProvisionContext, backends: list[ComputeResource],
                             network: NetworkResource | None) -> LoadBalancerResource: ...

    @abstractmethod
    def get_load_balancer(self, resource: LoadBalancerResource) -> LoadBalancerResource: ...

    @abstractmethod
    def delete_load_balancer(self, resource: LoadBalancerResource, ctx: ProvisionContext) -> None: ...

    # ---- reading and deleting any resource
    def refresh(self, resource):
        """The resource as the provider sees it now, by kind."""
        return getattr(self, f"get_{resource.kind.value}")(resource)

    def delete(self, resource, ctx: ProvisionContext) -> None:
        getattr(self, f"delete_{resource.kind.value}")(resource, ctx)

    def resource_status(self, resource) -> ResourceStatus:
        return self.refresh(resource).status

    @abstractmethod
    def resource_health(self, resource) -> Health: ...

    @abstractmethod
    def resource_usage(self, resource, minutes: int) -> Usage: ...
