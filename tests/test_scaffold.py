def test_python_version_detection_order():
    def version(texts, path=""):
        return scaffold.detect(list(texts), texts, path)["python"], scaffold.detect(list(texts), texts, path)["python_source"]

    everything = {"Dockerfile": "FROM python:3.14-slim\n", "platform.yaml": "python: '3.13'\n", ".python-version": "3.11.9\n",
                  "runtime.txt": "python-3.15.0\n", "pyproject.toml": "[project]\nrequires-python = '>=3.13'\n"}
    order = [("Dockerfile", "3.14"), ("platform.yaml", "3.13"), (".python-version", "3.11"), ("runtime.txt", "3.15"), ("pyproject.toml", "3.13")]
    texts = dict(everything)
    for source, expected in order:  # each source decides while it is there, then the next one does
        got, where = version(texts)
        assert got == expected and where.startswith(source), (source, got, where)
        del texts[source]
    assert version(texts) == ("3.12", "the platform's default")
    # Unsupported versions are skipped with a note and the next source decides.
    found = scaffold.detect(["Dockerfile", ".python-version"], {"Dockerfile": "FROM python:3.10-slim\n", ".python-version": "3.13\n"})
    assert found["python"] == "3.13" and any("3.10, which the platform does not support" in note for note in found["notes"])
    # requires-python ranges: 3.12 when it fits, else the lowest supported version that does; Poetry's ^ and ~ too.
    for specifier, expected in ((">=3.11", "3.12"), (">=3.13,<3.15", "3.13"), ("<3.12", "3.11"), ("~=3.14", "3.14"), ("==3.15.*", "3.15"),
                                ("^3.14", "3.14"), ("~3.13", "3.13"), (">=3.11,!=3.12.*", "3.11"), (">=3.11, <3.12.2", "3.11"), ("*", "3.12"),
                                (">=3.13.0rc1", "3.13"), (">=3.10,<3.11 || >=3.14", "3.14")):
        texts = {"pyproject.toml": f"[project]\nrequires-python = '{specifier}'\n"}
        assert version(texts)[0] == expected, specifier
    poetry = {"pyproject.toml": "[tool.poetry.dependencies]\npython = '^3.13'\n"}
    assert version(poetry)[0] == "3.13"
    impossible = scaffold.detect(["pyproject.toml"], {"pyproject.toml": "[project]\nrequires-python = '>=3.16'\n"})
    assert impossible["python"] == "3.12" and any("no supported version" in note for note in impossible["notes"])
    # A service in a folder reads its own version file first, then the repository's.
    nested = {"api/main.py": "", ".python-version": "3.14\n"}
    assert version(nested, "api") == ("3.14", ".python-version")
    assert version(dict(nested, **{"api/.python-version": "3.11\n"}), "api") == ("3.11", "api/.python-version")
    # The drafted files follow the detected version.
    drafted = scaffold.draft_files(["app.py", "requirements.txt", ".python-version"], dict(demo_texts(), **{".python-version": "3.14\n"}), name="lab-demo")
    assert f"FROM python:3.14-slim@{scaffold.BASE_IMAGES['3.14']}" in drafted["files"]["Dockerfile"]["content"]
    assert parse_spec(drafted["files"]["platform.yaml"]["content"]).python == "3.14"
    assert "python-version: '3.14'" in drafted["files"][".github/workflows/ci.yml"]["content"]


def test_a_missing_health_route_produces_a_review_note():
    texts = {"main.py": "from fastapi import FastAPI\n\napp = FastAPI()\n\n\n@app.get('/')\ndef index():\n    return {}\n",
             "requirements.txt": "fastapi==0.143.0\nuvicorn==0.54.0\n", "test_main.py": "client.get('/health')\n"}
    result = scaffold.draft_files(list(texts), texts, name="lab-demo")
    assert result["detected"]["health_path"] == "/health" and not result["detected"]["health_route_found"]  # a test is not a route
    assert any("No /health route was found" in note and "must add one" in note for note in result["review"])
    assert "tests/test_health.py" not in result["files"] and "test_main.py" in result["existing"]  # it already requests the path
    untested = dict(texts, **{"test_main.py": "def test_index():\n    pass\n"})
    result = scaffold.draft_files(list(untested), untested, name="lab-demo")
    assert 'client.get("/health")' in result["files"]["tests/test_health.py"]["content"]
    assert parse_spec(result["files"]["platform.yaml"]["content"]).health_path == "/health"
    # /healthz is routed, but Cloud Run reserves it: the drafts still use /health and say why.
    reserved = dict(texts, **{"main.py": texts["main.py"] + "\n\n@app.get('/healthz')\ndef healthz():\n    return {}\n"})
    result = scaffold.draft_files(list(reserved), reserved, name="lab-demo")
    assert result["detected"]["health_path"] == "/health" and any("Cloud Run reserves paths ending in z" in note for note in result["review"])
    # /healthcheck counts; a path platform.yaml declares is what the test checks.
    other = dict(texts, **{"main.py": texts["main.py"] + "\n\n@app.get('/healthcheck')\ndef check():\n    return {}\n"})
    assert scaffold.detect(list(other), other)["health_path"] == "/healthcheck"
    declared = dict(other, **{"platform.yaml": "name: lab-demo\nhealth_path: /ready\n"})
    result = scaffold.draft_files(list(declared), declared, name="lab-demo")
    assert 'client.get("/ready")' in result["files"]["tests/test_health.py"]["content"]
    assert any("health path /ready was not found" in note for note in result["review"])


def test_application_objects_factories_and_layouts():
    def found(texts, dependencies="fastapi==0.143.0\nuvicorn==0.54.0\n"):
        texts = dict(texts, **{"requirements.txt": dependencies})
        return scaffold.detect(list(texts), texts)

    flask_factory = found({"app/__init__.py": "from flask import Flask\n\ndef create_app():\n    app = Flask(__name__)\n    return app\n"},
                          "flask==3.1.3\ngunicorn==26.2.0\n")
    assert flask_factory["command"][-1] == "app:create_app()" and flask_factory["factory"]
    wsgi_module = found({"wsgi.py": "from app import create_app\napp = create_app()\n",
                         "app/__init__.py": "from flask import Flask\n\ndef create_app():\n    return Flask(__name__)\n"}, "flask==3.1.3\n")
    assert wsgi_module["application"] == "wsgi:app" and wsgi_module["framework"] == "flask" and wsgi_module["server"] == "gunicorn"
    assert not wsgi_module["server_listed"]
    fastapi_factory = found({"api/main.py": "import fastapi\n\ndef create_app():\n    return fastapi.FastAPI()\n"})
    assert fastapi_factory["command"] == ["uvicorn", "api.main:create_app", "--host", "0.0.0.0", "--port", "8080", "--factory"]  # noqa: S104 - Cloud Run's contract
    src = found({"src/lab/main.py": "from fastapi import FastAPI\napp: FastAPI = FastAPI(title='x')\n"})
    assert src["command"][-2:] == ["--app-dir", "src"] and src["application"] == "lab.main:app"
    assert any("pythonpath" in note for note in src["notes"])
    two = found({"main.py": "from fastapi import FastAPI\napp = FastAPI()\n", "admin.py": "from fastapi import FastAPI\nadmin = FastAPI()\n"})
