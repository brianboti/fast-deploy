def hadolint_command():
    """hadolint 2.15.1 as the platform pins it: the binary CI downloads by checksum, one on PATH, or the image already pulled."""
    for candidate in (os.environ.get("HADOLINT"), shutil.which("hadolint"), os.path.join(os.environ.get("RUNNER_TEMP", "/nonexistent"), "hadolint")):
        if candidate and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return [candidate]
    docker = shutil.which("docker")
    if docker and subprocess.run([docker, "image", "inspect", HADOLINT_IMAGE], capture_output=True, timeout=60).returncode == 0:
        return [docker, "run", "--rm", "-i", HADOLINT_IMAGE, "hadolint"]
    return None


@pytest.mark.skipif(hadolint_command() is None, reason="hadolint 2.15.1 is not available (CI downloads it; locally: docker pull " + HADOLINT_IMAGE + ")")
def test_drafted_dockerfiles_pass_hadolint():
    command = hadolint_command()
    for name, text in drafted_variants().items():
        run = subprocess.run(command + ["-"], input=text, capture_output=True, text=True, timeout=120)
        assert run.returncode == 0 and not run.stdout.strip(), f"{name}: {run.stdout}{run.stderr}"


def zizmor_command():
    beside = Path(sys.executable).parent / "zizmor"
    found = str(beside) if beside.is_file() else shutil.which("zizmor")
    return [found, "--no-progress", "--offline"] if found else None


@pytest.mark.skipif(zizmor_command() is None, reason="zizmor is not installed (it comes with requirements-dev.lock)")
def test_drafted_workflows_and_dependabot_pass_zizmor(tmp_path):
    root = scaffold.draft_files(["app.py", "requirements.txt"], demo_texts(), name="lab-demo")["files"]
    folder = scaffold.draft_files(["services/web/app.py", ".github/workflows/ci.yml"], {"services/web/app.py": FLASK_APP}, "services/web", "lab-notes")["files"]
    inputs = []
    for label, files in (("root", root), ("folder", folder)):
        for target, item in files.items():
            if target.startswith(".github/"):
                destination = tmp_path / label / target
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(item["content"])
                inputs.append(str(destination))
    assert len(inputs) == 4  # ci.yml and dependabot.yml at the root; ci-lab-notes.yml and dependabot.yml for the folder
    inputs += [str(scaffold.TEMPLATES / "ci.yml"), str(scaffold.TEMPLATES / "dependabot.yml")]  # the raw templates too (pre-commit lints them)
    run = subprocess.run(zizmor_command() + ["--persona", "auditor"] + inputs, capture_output=True, text=True, timeout=120)
    assert run.returncode == 0 and "No findings" in run.stdout + run.stderr, run.stdout + run.stderr
