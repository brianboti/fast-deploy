def test_lock_command_and_compile_lock_with_a_fake_runner():
    assert scaffold.lock_command("3.13") == "uv pip compile requirements.txt --universal --python-version 3.13 --generate-hashes -o requirements.lock"
    assert scaffold.lock_command("3.12", "services/api").startswith("cd services/api && uv pip compile requirements.txt ")
    contract = Path("docs/DEVELOPER-CONTRACT.md").read_text()
    assert scaffold.lock_command("3.12") in contract
    with pytest.raises(ValueError):
        scaffold.lock_command("3.10")
    calls = []
    lock = ("# This file was autogenerated by uv via the following command:\n#    " + scaffold.lock_command("3.13") + "\n"
            "fastapi==0.143.0 \\\n    --hash=sha256:" + "c" * 64 + "\n")

    def runner(args, stdin):
        calls.append((args, stdin))
        return lock

    result = scaffold.compile_lock("fastapi==0.143.0\n", "3.13", runner)
    assert result == {"text": lock, "command": scaffold.lock_command("3.13"), "error": None}
    args, stdin = calls[0]
    assert args[:4] == ["docker", "run", "--rm", "-i"] and "65532:65532" in args and scaffold.base_image("3.13") in args
    assert stdin == "fastapi==0.143.0\n" and "fastapi" not in " ".join(args)  # the requirements travel on stdin, never in a command
    script = args[-1]
    assert f"uv=={scaffold.UV_VERSION}" in script and all(digest in script for digest in scaffold.UV_HASHES) and "--require-hashes" in script
    assert "--universal --python-version 3.13 --generate-hashes -o requirements.lock" in script

    def missing(args, stdin):
        raise FileNotFoundError("docker")

    def failing(args, stdin):
        raise subprocess.CalledProcessError(1, args, stderr="error: No solution found when resolving dependencies\n")

    assert scaffold.compile_lock("x==1\n", "3.12", missing, "api") == {"text": None, "command": scaffold.lock_command("3.12", "api"),
                                                                        "error": "Docker is not installed on this machine"}
    failed = scaffold.compile_lock("x==1\n", "3.12", failing)
    assert failed["text"] is None and "No solution found" in failed["error"]
    assert scaffold.compile_lock("x==1\n", "3.12", lambda args, stdin: "x==1\n")["text"] is None  # no hashes: not a lock
    assert scaffold.compile_lock("  \n", "3.12", runner)["error"] == "requirements.txt is empty"


