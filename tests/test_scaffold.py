def test_a_compiled_lock_is_drafted_and_installed_with_hashes():
    lock = "# This file was autogenerated by uv via the following command:\nfastapi==0.143.0 \\\n    --hash=sha256:" + "a" * 64 + "\n"
    result = scaffold.draft_files(["app.py", "requirements.txt"], demo_texts(), name="lab-demo", lock_text=lock)
    assert result["files"]["requirements.lock"]["content"] == lock
    dockerfile = result["files"]["Dockerfile"]["content"]
    assert "COPY requirements.lock ./\nRUN pip install --no-cache-dir --require-hashes -r requirements.lock\n" in dockerfile
    assert not any("no requirements.lock" in note for note in result["review"])
    # A lock the repository already has wins over a compiled one, and the Dockerfile installs it.
    kept = scaffold.draft_files(["app.py", "requirements.txt", "requirements.lock"], demo_texts(), name="lab-demo", lock_text=lock)
    assert "requirements.lock" not in kept["files"] and "requirements.lock" in kept["existing"]
    assert "--require-hashes -r requirements.lock" in kept["files"]["Dockerfile"]["content"]


