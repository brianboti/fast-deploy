def test_a_second_service_in_the_same_repository_gets_its_own_ci_unless_one_runs_its_tests():
    paths = ["services/admin/main.py", "services/admin/requirements.txt", ".github/workflows/ci.yml", ".github/dependabot.yml"]
    texts = {"services/admin/main.py": "from fastapi import FastAPI\napp = FastAPI()\n", "services/admin/requirements.txt": "fastapi==0.143.0\n",
             ".github/workflows/ci.yml": "jobs:\n  tests:\n    steps:\n      - run: cd services/api && python -m pytest\n",
             ".github/dependabot.yml": "version: 2\nupdates:\n  - package-ecosystem: pip\n    directory: /services/api\n"}
    result = scaffold.draft_files(paths, texts, "services/admin", "lab-admin")
