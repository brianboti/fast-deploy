    assert ".github/dependabot.yml" in result["existing"] and ".github/dependabot.yml" not in result["files"]
    assert any("does not mention services/admin" in note for note in result["review"])
    covered = dict(texts, **{".github/workflows/ci.yml": "jobs:\n  t:\n    steps:\n      - run: cd services/admin && python -m pytest\n"})
    again = scaffold.draft_files(paths, covered, "services/admin", "lab-admin")
