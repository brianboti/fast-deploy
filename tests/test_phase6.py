def test_publish_sets_variables_through_the_api_or_tells_the_operator_what_to_set():
    outputs = {"github_repository": {"value": "lab/demo"},
               "github_environment_variables": {"value": {"GCP_PROJECT_ID": "test-project", "WIF_PROVIDER": "projects/1/locations/global/workloadIdentityPools/p/providers/github"}}}
    text, ok = publish(outputs, token=None)
    assert ok and "set these on the environment by hand" in text and "| GCP_PROJECT_ID | `test-project` |" in text
    calls = []

    def fake(method, url, token, body=None):
        calls.append((method, url.rsplit("/", 2)[-2:], body))
        if method == "PATCH" and body["name"] == "WIF_PROVIDER":
            return 404, None  # not there yet: created instead
        return (204, None) if method == "PATCH" else (201, None)
    text, ok = publish(outputs, token="t", request=fake)
    assert ok and "- GCP_PROJECT_ID: updated" in text and "- WIF_PROVIDER: created" in text
    assert [c[0] for c in calls] == ["PATCH", "PATCH", "POST"] and calls[0][1] == ["variables", "GCP_PROJECT_ID"]
    text, ok = publish(outputs, token="t", request=lambda *a, **k: (403, None))
    assert not ok and "failed (HTTP 403)" in text and "Variables: write" in text
    with pytest.raises(ValueError):
        publish({"github_repository": {"value": "bad repo"}, "github_environment_variables": {"value": {}}}, token="t", request=fake)
    with pytest.raises(ValueError, match="render the root again"):
        publish({"github_environment_variables": {"value": {}}}, token="t", request=fake)


def test_controller_renders_the_root_from_the_spec_and_opens_the_platform_pull_request(tmp_path):
    cfg = config(tmp_path, platform={"repository": "lab/platform"})
    gh = FakeGitHub()
    gh.spec = {"name": "demo", "reviewed": True, "health_path": "/ready"}
    c = Controller(cfg, gh, Store(cfg.database))
    p = cfg.principals[0]
    rendered = c.render_infrastructure(p, "demo")
    assert rendered["directory"] == "infra/gcp/apps/demo" and rendered["note"] is None
    assert 'health_path                  = "/ready"' in rendered["files"]["main.tf"] and 'github_repository_id         = "123"' in rendered["files"]["main.tf"]
    assert 'bucket = "test-project-tfstate"' in rendered["files"]["backend.tf"]
    proposed = c.propose_infrastructure(p, "demo")
    assert proposed["pull_request"]["number"] == 7
    assert proposed["files"] == ["infra/gcp/apps/demo/.terraform.lock.hcl", "infra/gcp/apps/demo/backend.tf", "infra/gcp/apps/demo/main.tf", "infra/gcp/apps/demo/outputs.tf"]
    assert gh.platform_prs[-1]["repository"] == "lab/platform" and gh.platform_prs[-1]["branch"] == "lab-deploy/infra-demo"

    class NoSpec(FakeGitHub):
        def file(self, app, sha, filename):
            raise httpx.HTTPStatusError("missing", request=httpx.Request("GET", "https://x"), response=httpx.Response(404))
    rendered = Controller(cfg, NoSpec(), Store(cfg.database)).render_infrastructure(p, "demo")
    assert "Defaults used" in rendered["note"] and 'health_path                  = "/health"' in rendered["files"]["main.tf"]
    off = config(tmp_path, platform={"repository": "lab/platform"}, live_dispatch=False)
    with pytest.raises(ValueError, match="Writes are disabled"):
        Controller(off, FakeGitHub(), Store(off.database)).propose_infrastructure(p, "demo")
    with pytest.raises(ValueError, match="platform.repository"):
        Controller(config(tmp_path), FakeGitHub(), Store(cfg.database)).propose_infrastructure(p, "demo")


def test_cli_renders_and_writes_a_root_and_checks_a_plan(tmp_path, monkeypatch, capsys):
    cfg_path = tmp_path / "config.yaml"
    cfg_path.write_text(yaml.safe_dump(settings(tmp_path)))
    monkeypatch.setenv("LAB_CONFIG", str(cfg_path))
    monkeypatch.setattr("labdeploy.github.GitHub", FakeGitHub)
    parser = cli.build_parser()
    cli.run(parser, parser.parse_args(["infra", "render", "demo", "--write", "--root", str(tmp_path / "apps")]))
    written = sorted(p.name for p in (tmp_path / "apps" / "demo").iterdir())
    assert written == ["backend.tf", "main.tf", "outputs.tf"] and "apps/demo/main.tf" in capsys.readouterr().out
    (tmp_path / "project").mkdir()
    (tmp_path / "project" / ".terraform.lock.hcl").write_text("# lock\n")
    cli.run(parser, parser.parse_args(["infra", "render", "demo", "--write", "--root", str(tmp_path / "apps")]))
    assert (tmp_path / "apps" / "demo" / ".terraform.lock.hcl").read_text() == "# lock\n"
    cli.run(parser, parser.parse_args(["infra", "render", "demo"]))
    assert "# ---- infra/gcp/apps/demo/backend.tf" in capsys.readouterr().out
    plan = tmp_path / "plan.json"
    plan.write_text(json.dumps({"resource_changes": []}))
    with pytest.raises(SystemExit) as stop:
        cli.run(parser, parser.parse_args(["infra", "check", str(plan)]))
    assert stop.value.code == 0
    with pytest.raises(SystemExit) as stop:
        cli.run(parser, parser.parse_args(["infra", "summary", str(plan), "--app", "demo"]))
    assert stop.value.code == 0 and "lab-deploy-infra:demo" in capsys.readouterr().out
