def test_summary_and_comment_describe_the_plan_and_the_verdict():
    plan = {"resource_changes": [
        change("a", "google_cloud_run_v2_service", ["create"], {"location": "us-central1", "labels": {"lab-deploy-app": "demo"}}),
        change("b", "google_monitoring_alert_policy", ["update"], {}),
        change("c", "google_service_account", ["delete", "create"], {}),
        change("d", "google_project_iam_member", ["no-op"], {}),
    ]}
    assert summary(plan) == {"counts": {"create": 1, "update": 1, "delete": 0, "replace": 1}, "lines": ["+ a", "~ b", "-/+ c"]}
    text = comment("demo", plan, check_plan(plan))
    assert text.startswith("<!-- lab-deploy-infra:demo -->") and "1 to add, 1 to change, 0 to destroy, 1 to replace" in text and "Policy: passed" in text
    blocked = comment("demo", plan, [{"rule": "no_data_loss", "address": "x", "detail": "never"}])
    assert "Policy: blocked" in blocked and "`x`: never (no_data_loss)" in blocked
    assert "No changes." in comment("demo", {"resource_changes": []}, [])


def test_module_entry_point_exits_two_on_violations(tmp_path, capsys):
    plan = tmp_path / "plan.json"
    plan.write_text(json.dumps({"resource_changes": [change("k", "google_service_account_key", ["create"], {})]}))
    assert main(["check", str(plan)]) == 2
    assert "no_service_account_keys" in capsys.readouterr().out
    plan.write_text(json.dumps({"resource_changes": []}))
    assert main(["check", str(plan)]) == 0
    assert main(["summary", str(plan), "demo"]) == 0 and "lab-deploy-infra:demo" in capsys.readouterr().out
    plan.write_text(json.dumps({"github_environment_variables": {"value": {}}}))
    assert main(["publish", str(plan)]) == 1 and "Outputs not published" in capsys.readouterr().out
    assert main(["nonsense"]) == 1


