def settings(tmp_path, **extra):
    base = {"live_dispatch": True, "database": str(tmp_path / "db"),
            "applications": {"demo": {"repository": "lab/demo", "service": "demo", "target": TARGET}},
            "principals": [{"name": "m", "token_sha256": hashlib.sha256(b"test-token").hexdigest(), "applications": ["demo"], "can_deploy": True}]}
    base.update(extra)
    return base


def config(tmp_path, **extra):
    return Config.model_validate(settings(tmp_path, **extra))

ROOT = dict(project_id="test-project", region="us-central1", state_bucket="test-project-tfstate", github_repository="lab/demo",
            github_repository_id="123", github_owner_id="45", bootstrap_image="us-docker.pkg.dev/cloudrun/container/hello@sha256:" + "a" * 64)


def change(address, kind, actions, after=None):
    return {"address": address, "type": kind, "change": {"actions": actions, "after": after}}


def test_app_root_writes_three_literal_files_with_the_shared_values_from_the_project_state():
    files = app_root("demo", health_path="/health", settings={"instance_alert_count": 4}, **ROOT)
    assert sorted(files) == ["backend.tf", "main.tf", "outputs.tf"]
    assert 'bucket = "test-project-tfstate"' in files["backend.tf"] and 'prefix = "apps/demo/staging"' in files["backend.tf"]
    main_tf = files["main.tf"]
    assert 'source                       = "../../modules/service"' in main_tf
    assert 'prefix = "project/staging"' in main_tf and "data.terraform_remote_state.project.outputs.alert_channels" in main_tf
    assert 'github_repository_id         = "123"' in main_tf and "instance_alert_count         = 4" in main_tf
    assert "registry_cleanup_dry_run     = true" in main_tf and 'health_path                  = "/health"' in main_tf
    assert "image_vulnerability_scanning = data.terraform_remote_state.project.outputs.image_vulnerability_scanning" in main_tf
    assert files["outputs.tf"].count("output ") == 6 and 'output "github_repository" { value = "lab/demo" }' in files["outputs.tf"]
    assert files["main.tf"].startswith("# Generated by `lab-deploy infra render demo`")
    other = app_root("demo", environment="qa", **ROOT)
    assert 'prefix = "apps/demo/qa"' in other["backend.tf"] and 'prefix = "project/qa"' in other["main.tf"]


