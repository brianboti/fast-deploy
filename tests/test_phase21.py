def test_a_workspace_member_installs_from_the_roots_lockfile_and_builds_in_its_folder():
    package = {"name": "api", "version": "1.0.0", "scripts": {"start": "node server.js"}, "dependencies": {"express": "^4", "@mono/shared": "workspace:*"}}
    files = {"package.json": json.dumps({"name": "mono", "private": True}), "pnpm-workspace.yaml": "packages:\n  - 'apps/*'\n  - 'packages/*'\n",
             "pnpm-lock.yaml": pnpm_lock({"express": "^4"}, importers=["apps/api", "packages/shared"]), "apps/api/package.json": json.dumps(package),
             "apps/api/server.js": SERVER, "packages/shared/package.json": json.dumps({"name": "@mono/shared"})}
    result = node_read(files, "apps/api")
    assert not result["refusals"], result["refusals"]
    assert result["lock"]["from"] == "pnpm-lock.yaml" and result["lock"]["member"] and result["spec"].build.context == "repository"
    assert "from the workspace root" in choice(result, "Dependencies")["value"] and any("installed from the root's lockfile" in note for note in result["notes"])
    unlisted = dict(files, **{"pnpm-lock.yaml": pnpm_lock({"express": "^4"}, importers=["packages/shared"])})
    assert refused(node_read(unlisted, "apps/api"), "does not list apps/api as a package of the workspace")
    root = node_read(files)
    assert refused(root, "is a workspace of several packages (apps/api, packages/shared) and starts nothing itself")
    assert "path apps/api" in root["refusals"][0]["fix"]
    nx = node_read(node_repo(start=None, files={"nx.json": "{}", "server.js": None}))
    assert refused(nx, "is a repository managed by nx")


