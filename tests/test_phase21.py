INTEGRITY = "sha512-" + "B" * 86 + "=="


def pnpm_lock(deps, extra_packages="", version="9.0", importers=None):
    """A pnpm lockfile: every dependency from the registry with an integrity."""
    lines = [f"lockfileVersion: '{version}'", "", "importers:", "", "  .:", "    dependencies:"]
    for name, spec in deps.items():
        lines += [f"      {name}:", f"        specifier: {spec}", "        version: 1.2.3"]
    for folder in importers or []:
        lines += [f"  {folder}:", "    dependencies: {}"]
    lines += ["", "packages:", ""]
    for name in deps:
        lines += [f"  {name}@1.2.3:", f"    resolution: {{integrity: {INTEGRITY}}}", ""]
    return "\n".join(lines) + extra_packages + "\n"


def yarn1_lock(deps):
    blocks = ["# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.", "# yarn lockfile v1", "", ""]
    for name, spec in deps.items():
        blocks += [f'"{name}@{spec}":' if name.startswith("@") else f"{name}@{spec}:", '  version "1.2.3"',
                   f'  resolved "https://registry.yarnpkg.com/{name}/-/{name.split("/")[-1]}-1.2.3.tgz#abc"', f"  integrity {INTEGRITY}", ""]
    return "\n".join(blocks)


def berry_lock(deps, members=(), metadata="10"):
    blocks = ['# This file is generated by running "yarn install" inside your project.', "", "__metadata:", f"  version: {metadata}", "  cacheKey: 10c0", ""]
    for name, spec in deps.items():
        blocks += [f'"{name}@npm:{spec}":', "  version: 1.2.3", f'  resolution: "{name}@npm:1.2.3"', "  checksum: 10c0/abcdef", "  languageName: node",
                   "  linkType: hard", ""]
    for folder in members:
        blocks += [f'"{folder.rsplit("/", 1)[-1]}@workspace:{folder}":', "  version: 0.0.0-use.local", f'  resolution: "{folder.rsplit("/", 1)[-1]}@workspace:{folder}"',
                   "  languageName: unknown", "  linkType: soft", ""]
    return "\n".join(blocks)


def bun_lock(deps, members=()):
    packages = {name: [f"{name}@1.2.3", "", {}, INTEGRITY] for name in deps}
    workspaces = {"": {"name": "svc", "dependencies": deps}, **{folder: {"name": folder.rsplit("/", 1)[-1]} for folder in members}}
    return "// bun.lock\n" + json.dumps({"lockfileVersion": 1, "workspaces": workspaces, "packages": packages}, indent=2) + "\n"


def service(start="node server.js", deps=None, lock="pnpm", files=None, extra=None, scripts=None):
    """A Node.js service with another manager's lockfile instead of npm's."""
    deps = {"express": "^4.21.2"} if deps is None else deps
    result = node_repo(start=start, deps=deps, extra=extra, lock=False, files=files)
    if scripts:
        package = json.loads(result["package.json"])
        package["scripts"] = {**package.get("scripts", {}), **scripts}
        result["package.json"] = json.dumps(package)
    if lock == "pnpm":
        result.setdefault("pnpm-lock.yaml", pnpm_lock(deps))
    elif lock == "yarn1":
        result.setdefault("yarn.lock", yarn1_lock(deps))
    elif lock == "yarn":
        result.setdefault("yarn.lock", berry_lock(deps))
        result.setdefault(".yarnrc.yml", "nodeLinker: node-modules\n")
    elif lock == "bun":
        result.setdefault("bun.lock", bun_lock(deps))
    elif lock == "npm":
        result.setdefault("package-lock.json", lockfile(json.loads(result["package.json"])))
    return result


# ---- 21.1 the other managers' lockfiles, read into one view
def test_pnpm_yarn_and_bun_lockfiles_read_into_the_same_view_as_npms():
    view, problem = node.read_lock("pnpm-lock.yaml", pnpm_lock({"express": "^4"}, importers=["web"]) + "  mylib@https://codeload.github.com/x/y/tar.gz/abc:\n"
                                   "    resolution: {tarball: https://codeload.github.com/x/y/tar.gz/abc}\n  sharp@0.32.6:\n    resolution: {integrity: sha512-x}\n"
                                   "    requiresBuild: true\n  node@runtime:24.21.0:\n    resolution: {type: variations}\n")
    assert problem is None and view["manager"] == "pnpm" and view["members"] == ["web"]
    assert view["packages"]["express@1.2.3"]["source"] == "registry" and view["packages"]["node@runtime:24.21.0"]["source"] == "runtime"
    assert node.view_problems(view) == [("mylib", "comes from a git repository")] and node.view_scripts(view) == ["sharp@0.32.6"]
    assert node.view_names(view)["sharp"] == "0.32.6"
    v1, problem = node.read_lock("yarn.lock", yarn1_lock({"express": "^4.21.2", "@types/node": "^20"}))
    assert problem is None and v1["manager"] == "yarn1" and {entry["name"] for entry in v1["packages"].values()} == {"express", "@types/node"}
    assert node.view_problems(v1) == [] and node.view_scripts(v1) is None  # Yarn's lockfile does not say which packages run a script
    berry, problem = node.read_lock("yarn.lock", berry_lock({"express": "^4"}, members=["packages/api"]))
    assert problem is None and berry["manager"] == "yarn" and berry["members"] == ["packages/api"] and node.view_problems(berry) == []
    patch = "left-pad@patch:left-pad@npm%3A1.3.0#./.yarn/patches/left-pad.patch"
    patched = berry_lock({"express": "^4"}) + f'"{patch}":\n  version: 1.3.0\n  resolution: "{patch}"\n  checksum: 10c0/1\n'
    assert node.view_problems(node.read_lock("yarn.lock", patched)[0]) == [("left-pad", "is patched in the repository (patch:), so what installs is not what the registry published")]
    bun, problem = node.read_lock("bun.lock", bun_lock({"express": "^4"}, members=["packages/a"]))
    assert problem is None and bun["manager"] == "bun" and bun["members"] == ["packages/a"] and node.view_problems(bun) == []
    assert node.read_lock("bun.lockb", "\x00")[1] == "is Bun's old binary lockfile, which only Bun reads"
    assert node.read_lock("pnpm-lock.yaml", "lockfileVersion: '5.4'\n")[1].startswith("is pnpm lockfile version 5.4")
    assert node.read_lock("yarn.lock", "not a lockfile\n")[1] == "is not a Yarn lockfile"
    npm, _ = node.read_lock("package-lock.json", lockfile({"name": "x", "dependencies": {"express": "^4"}}))
    assert npm["manager"] == "npm" and node.view_names(npm) == {"express": "1.2.3"}
    assert node.jsonc_loads('{ // c\n "a": [1, 2,], /* x */ "b": "//not a comment", }') == {"a": [1, 2], "b": "//not a comment"}


def test_the_reader_installs_each_lockfile_with_its_own_manager_frozen_and_with_scripts_off():
    pnpm_version = scaffold.MANAGER_PINS["pnpm"][0]
    result = node_read(service(lock="pnpm"))
    assert not result["refusals"] and result["lock"]["manager"] == "pnpm" and result["lock"]["action"] == "use"
    assert choice(result, "Dependencies")["value"] == (f"pnpm-lock.yaml, installed with `pnpm install --frozen-lockfile --ignore-scripts` (pnpm {pnpm_version}, "
                                                        "the platform's pin, installed by version and integrity; every install script off)")
    assert any("installed frozen by pnpm: a lockfile behind package.json stops the build" in note for note in result["notes"])
    yarn1 = node_read(service(lock="yarn1"))
    assert not yarn1["refusals"] and yarn1["lock"]["manager"] == "yarn1" and "`yarn install --frozen-lockfile --ignore-scripts --non-interactive`" in choice(yarn1, "Dependencies")["value"]
    berry = node_read(service(lock="yarn"))
    assert not berry["refusals"] and berry["lock"]["manager"] == "yarn" and "`yarn install --immutable`" in choice(berry, "Dependencies")["value"]
    pnp = node_read(service(lock="yarn", files={".yarnrc.yml": "yarnPath: .yarn/releases/yarn.cjs\n"}))
    assert refused(pnp, "installs with Yarn's Plug'n'Play") and "nodeLinker: node-modules" in pnp["refusals"][0]["fix"]
    bun = node_read(service(lock="bun"))
    assert not bun["refusals"] and bun["lock"]["manager"] == "bun" and "`bun install --frozen-lockfile --ignore-scripts`" in choice(bun, "Dependencies")["value"]
    assert refused(node_read(service(lock="pnpm", files={"yarn.lock": yarn1_lock({"express": "^4"})})), "more than one lockfile (yarn.lock, pnpm-lock.yaml)")
    git = node_read(service(lock="pnpm", files={"pnpm-lock.yaml": pnpm_lock({"express": "^4"}) + "  dep@https://codeload.github.com/x/y/tar.gz/abc:\n    resolution: {tarball: https://codeload.github.com/x/y/tar.gz/abc}\n"}))
    assert refused(git, "holds packages pnpm would install without checking them against the npm registry: dep comes from a git repository")
    # A dependency audit reads the same lockfile with the same checks.
    summary = scan.osv_summary({"results": []}, 0, pnpm_lock({"express": "^4"}), "pnpm-lock.yaml")
    assert summary["packages"] == 1 and summary["lockfile"] == "read" and summary["lock_problems"] == [] and scan.osv_verdict(summary) is None


def test_the_managers_commands_and_pins():
    for manager, commands in node.MANAGER_COMMANDS.items():
        assert {"frozen", "production", "prune", "rebuild", "run", "lockfiles", "title"} <= set(commands)
        assert "--ignore-scripts" in commands["frozen"] or manager == "yarn"  # Yarn 2+ turns scripts off through YARN_ENABLE_SCRIPTS
    assert set(scaffold.MANAGER_PINS) == {"pnpm", "yarn", "yarn1", "bun"} and set(scaffold.MANAGER_PACKAGES) == set(scaffold.MANAGER_PINS)
    for manager, (version, integrity) in scaffold.MANAGER_PINS.items():
        assert version.count(".") == 2 and integrity.startswith("sha512-") and pins.BY_KEY[manager].kind == "npm"
        assert pins.BY_KEY[manager].source == scaffold.MANAGER_PACKAGES[manager][0]
    lines = scaffold.manager_install_lines("pnpm", "/tmp/m")
    version, integrity = scaffold.MANAGER_PINS["pnpm"]
    assert any(f"npm install --no-audit --no-fund --ignore-scripts --loglevel=error pnpm@{version}" in line for line in lines)
    assert any("node -e" in line and integrity in line for line in lines) and lines[-1] == "chmod +x /tmp/m/bin/pnpm"
    assert any("exec node /tmp/m/node_modules/pnpm/bin/pnpm.cjs \"$@\"" in line for line in lines)
    assert scaffold.manager_install_lines("npm", "/tmp/m") == []
    assert scaffold.manager_install_lines("bun", "/tmp/m", wrapper=False)[-1].startswith("chmod +x /tmp/m/node_modules/@oven/bun-linux-x64/bin/bun")
    assert scaffold.image_command("pnpm", "pnpm install --frozen-lockfile") == "node /opt/manager/node_modules/pnpm/bin/pnpm.cjs install --frozen-lockfile"
    assert scaffold.image_command("yarn1", "yarn install --frozen-lockfile") == "node /opt/manager/node_modules/yarn/bin/yarn.js install --frozen-lockfile"
    assert scaffold.image_command("yarn1", "npm rebuild --ignore-scripts=false") == "npm rebuild --ignore-scripts=false"
    assert scaffold.image_command("npm", "npm ci") == "npm ci"
    # The weekly refresh follows each manager's line on the registry; pnpm's own install script (skipped, scripts off) holds nothing back.
    pin, web = pins.BY_KEY["pnpm"], FakeWeb()
    web.routes["https://registry.npmjs.org/pnpm"] = {"versions": {}, "time": {}}
    npm_registry(web, {"12.900.0": (19, {"scripts": {"postinstall": "node install.js"}}), "12.800.0": (54, {})})
    document = web.routes.pop("https://registry.npmjs.org/npm")
    web.routes["https://registry.npmjs.org/pnpm"] = document
    found = pins.from_npm(pin, {"version": "12.800.0"}, web, NOW)
    assert found.status == "update" and found.new["version"] == "12.900.0"


