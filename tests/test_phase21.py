# ---- the manager's own release (review of #140): packageManager first, the pin only for the formats it installs frozen
def test_package_manager_names_the_release_that_installs_and_the_pin_covers_only_its_own_format(tmp_path, capsys):
    hexdigest = "ab" * 64
    spec = node.manager_spec({"packageManager": f"pnpm@9.15.0+sha512.{hexdigest}"})
    assert spec["manager"] == "pnpm" and spec["version"] == "9.15.0" and spec["integrity"] == "sha512-" + __import__("base64").b64encode(bytes.fromhex(hexdigest)).decode()
    assert node.manager_spec({"packageManager": "yarn@1.22.22"})["manager"] == "yarn1" and node.manager_spec({"packageManager": "yarn@3.8.7"})["manager"] == "yarn"
    assert node.manager_spec({"packageManager": "pnpm@^9"}) is None and node.manager_spec({"packageManager": "yarn@4.5.3+sha224.abc"})["integrity"] is None
    # pnpm 8's lockfile 6.0 and Yarn 3's metadata 6 are refused without packageManager: pnpm 12 and Yarn 4.18 cannot install them frozen.
    old_pnpm = node_read(service(lock="pnpm", files={"pnpm-lock.yaml": pnpm_lock({"express": "^4"}, version="6.0")}))
    assert refused(old_pnpm, "is lockfile version 6, which the platform's pnpm") and "packageManager" in old_pnpm["refusals"][0]["fix"]
    old_yarn = node_read(service(lock="yarn", files={"yarn.lock": berry_lock({"express": "^4"}, metadata="6")}))
    assert refused(old_yarn, "is Yarn lockfile format 6, which the platform's Yarn")
    # With packageManager naming the release that wrote them, that release installs them, held to the hash it carries.
    named = node_read(service(lock="pnpm", files={"pnpm-lock.yaml": pnpm_lock({"express": "^4"}, version="6.0")},
                              extra={"packageManager": f"pnpm@8.15.9+sha512.{hexdigest}"}))
    assert not named["refusals"] and named["lock"]["manager_release"] == {"version": "8.15.9", "integrity": spec["integrity"]}
    assert "pnpm 8.15.9 from packageManager, installed by version and checked against the sha512 packageManager carries" in choice(named, "Dependencies")["value"]
    yarn3 = node_read(service(lock="yarn", files={"yarn.lock": berry_lock({"express": "^4"}, metadata="6")}, extra={"packageManager": "yarn@3.8.7"}))
    assert not yarn3["refusals"] and "the integrity the npm registry publishes" in choice(yarn3, "Dependencies")["value"]
    other = node_read(service(lock="pnpm", extra={"packageManager": "yarn@4.9.2"}))
    assert refused(other, "names yarn in packageManager, but the lockfile is pnpm-lock.yaml")
    # The install lines and the image take that release; with no sha512 they hold the version and npm's registry check.
    lines = scaffold.manager_install_lines("yarn", "/tmp/m", release={"version": "3.8.7", "integrity": ""})
    assert any("@yarnpkg/cli-dist@3.8.7" in line for line in lines) and any(line.endswith(" ''") and "node -e" in line for line in lines)
    app = tmp_path / "app"
    app.mkdir()
    (app / "package.json").write_text(json.dumps({"name": "svc", "packageManager": f"pnpm@8.15.9+sha512.{hexdigest}", "dependencies": {"express": "^4"}}))
    (app / "pnpm-lock.yaml").write_text(pnpm_lock({"express": "^4"}, version="6.0"))
    facts = scaffold.node_facts(app, "", "24")
    assert facts["version"] == "8.15.9" and facts["integrity"] == spec["integrity"]
    text = scaffold.platform_dockerfile(node_spec(), True, "pnpm-lock.yaml", facts)
    assert "pnpm@8.15.9" in text and spec["integrity"] in text and scaffold.MANAGER_PINS["pnpm"][0] not in text
    assert scaffold.main(["node-facts", str(app)]) == 0
    out = capsys.readouterr().out
    assert "VERSION=8.15.9\n" in out and f"INTEGRITY={spec['integrity']}\n" in out
    assert scaffold.main(["manager-install", "pnpm", "/tmp/m", "--version", "8.15.9", "--integrity", spec["integrity"]]) == 0
    assert "pnpm@8.15.9" in capsys.readouterr().out
    assert scaffold.main(["manager-install", "pnpm", "/tmp/m", "--version", "8.15.9", "--integrity", "sha1-abc"]) == 1
