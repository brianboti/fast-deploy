def test_the_platforms_table_drafts_build_scripts_at_the_locked_version():
    assert node.needed_scripts({"sharp": "0.32.6", "bcrypt": "5.1.1", "canvas": "2.11.2", "esbuild": "0.19.0", "puppeteer": "23.0.0"}) == [
        ("canvas@2.11.2", "node-pre-gyp fetches or builds its binary at install (every version)"),
        ("puppeteer@23.0.0", "its install script downloads a browser, which Cloud Run cannot run anyway: use puppeteer-core (every version)"),
        ("sharp@0.32.6", "its install script downloaded or built libvips; 0.33 and later ship the binary as optional dependencies (below 0.33)")]
    assert node.approved_scripts({"pnpm": {"onlyBuiltDependencies": ["sharp"]}}, "pnpm") == (["sharp"], [], [])
    assert node.approved_scripts({"dependenciesMeta": {"sharp@0.32.6": {"built": True}, "canvas": {"built": True}}}, "yarn") == (["canvas"], ["sharp@0.32.6"], [])
    assert node.approved_scripts({"trustedDependencies": ["canvas"]}, "bun") == (["canvas"], [], [])
    assert node.ecosystem_script('{"apps": [{"script": "src/index.js"}]}') == "src/index.js" and node.ecosystem_script('{"apps": [{"script": "x.py", "interpreter": "python"}]}') is None
    # pnpm 9's lockfile does not say which packages run a script: the table decides, at the locked version; pnpm's own approvals join.
    lock = pnpm_lock({"express": "^4", "canvas": "^2", "esbuild": "^0.19"}).replace("  canvas@1.2.3:", "  canvas@2.11.2:").replace("  esbuild@1.2.3:", "  esbuild@0.19.0:")
    result = node_read(service(deps={"express": "^4", "canvas": "^2", "esbuild": "^0.19"}, lock="pnpm", files={"pnpm-lock.yaml": lock},
                               extra={"pnpm": {"onlyBuiltDependencies": ["esbuild"]}}))
    assert result["spec"].build.scripts == ["canvas@2.11.2", "esbuild@0.19.0"]
    assert "from the platform's table of packages that need theirs on Cloud Run, for the merge to approve: canvas@2.11.2" in choice(result, "Install scripts")["value"]
    plain = node_read(service(lock="yarn1"))
    assert plain["spec"].build.scripts == [] and any("does not record which packages have install scripts" in note for note in plain["notes"])


