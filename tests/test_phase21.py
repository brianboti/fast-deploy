def test_the_build_plan_knows_the_frameworks_outputs_and_starts():
    plan = node.build_plan({"scripts": {"build": "next build", "start": "next start"}, "dependencies": {"next": "16"}}, lambda p: p == "next.config.ts",
                           {"next.config.ts": "const config = { output: 'standalone' }"}, "pnpm", "24")
    assert plan["build"] == ["pnpm", "run", "build"] and plan["start"] == ["node", "server.js"] and plan["env"] == {"HOSTNAME": "0.0.0.0"}  # noqa: S104
    assert plan["copy"] == [".next/standalone", ".next/static", "public"] and plan["standalone"]
    served = node.build_plan({"dependencies": {"next": "16"}}, lambda p: False, {}, "npm", "24")
    assert served["build"] == ["node", "node_modules/.bin/next", "build"] and served["start"] == ["node", "node_modules/next/dist/bin/next", "start", "-H", "0.0.0.0", "-p", "$PORT"]  # noqa: S104
    nest = node.build_plan({"scripts": {"build": "nest build"}, "dependencies": {"@nestjs/core": "^12"}}, lambda p: False, {}, "npm", "24")
    assert nest["start"] == ["node", "dist/main.js"] and nest["framework"] == "NestJS"
    svelte = node.build_plan({"scripts": {"build": "vite build"}, "devDependencies": {"@sveltejs/kit": "^2", "@sveltejs/adapter-node": "^5"}}, lambda p: False, {}, "npm", "24")
    assert svelte["start"] == ["node", "build"] and svelte["env"] == {"HOST": "0.0.0.0"}  # noqa: S104
    site = node.build_plan({"scripts": {"build": "vite build"}, "devDependencies": {"@sveltejs/kit": "^2"}}, lambda p: False, {}, "npm", "24")
    assert "front-end site with no server of its own" in site["problem"]
    assert "Strapi, whose build reads its secret keys" in node.build_plan({"dependencies": {"@strapi/strapi": "5"}}, lambda p: False, {}, "npm", "24")["problem"]
    options = {"tsconfig.json": '{ "extends": "./tsconfig.base.json", "compilerOptions": { /* out */ "outDir": "./dist", "rootDir": "./src", } }',
               "tsconfig.base.json": '{"compilerOptions": {"erasableSyntaxOnly": true}}'}
    assert node.tsconfig_options(options) == {"erasableSyntaxOnly": True, "outDir": "./dist", "rootDir": "./src"}
    assert node.built_path("src/index.ts", {"outDir": "dist"}) == "dist/index.js" and node.built_path("src/a.mts", {"outDir": "out", "rootDir": "."}) == "out/src/a.mjs"
    strip = node.build_plan({}, lambda p: p == "tsconfig.json", {"tsconfig.json": '{"compilerOptions": {"erasableSyntaxOnly": true}}'}, "npm", "24", ["node", "src/index.ts"])
    assert strip["build"] is None and strip["start"] == ["node", "src/index.ts"] and "type stripping" in strip["why"]
    tsc = node.build_plan({"scripts": {"build": "tsc"}, "devDependencies": {"typescript": "~6"}}, lambda p: p == "tsconfig.json",
                          {"tsconfig.json": '{"compilerOptions": {"outDir": "dist"}}'}, "npm", "22", ["node", "src/server.ts"])
    assert tsc["build"] == ["npm", "run", "build"] and tsc["start"] == ["node", "dist/server.js"] and "on Node.js 22" in tsc["why"]
    bare = node.build_plan({"devDependencies": {"typescript": "~6"}}, lambda p: False, {}, "pnpm", "24", ["node", "src/server.ts"])
    assert bare["build"] == ["node", "node_modules/.bin/tsc"]
    missing = node.build_plan({"scripts": {"build": "esbuild src/index.js --outfile=dist/index.js"}}, lambda p: False, {}, "npm", "24", ["node", "dist/index.js"])
    assert missing["build"] == ["npm", "run", "build"] and "the build script makes it" in missing["why"]


