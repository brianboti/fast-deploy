    assert list(files) == [contract_path("asis")] and only_commit_moved(gh.repos[PLATFORM]["files"][contract_path("asis")], files[contract_path("asis")])[0]
    assert "checks" in request["waiting"]  # auto-merge allows it; GitHub has not said it is mergeable yet
