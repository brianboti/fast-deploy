    assert c.store.latest_plan("asis")["sha"] == gh.sha and c.contract_tick()["asis"].startswith("up to date")  # released once
    # A newer request supersedes an older one; with auto-merge off a person merges it.
    gh.sha = "b" * 40
    c.config.current.onboarding.auto_merge = False
    request = c.deploy_latest(brian, "asis")["release_request"]
    assert request["waiting"].startswith("a person to merge") and gh.merges[-1] != (PLATFORM, request["pull_request"])
    gh.sha = "c" * 40
    newer = c.deploy_latest(brian, "asis")["release_request"]
