    c.onboard(brian, "lab/asis", as_is=True)
    number = c.onboarding_status(brian, "asis")["steps"]["contract"]["pull_request"]
    gh.merge_pull_request(PLATFORM, number, "x")
    c.advance_onboarding("asis")
    gh.runs[(PLATFORM, "infra-plan.yml", "d" * 40)] = [{"id": 1, "status": "completed", "conclusion": "success", "url": "u1", "head_sha": "d" * 40}]
    gh.comments[(PLATFORM, number + 1)] = ["<!-- lab-deploy-infra:asis -->\n**Policy: passed.**"]
    c.advance_onboarding("asis")
