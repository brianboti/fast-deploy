def fake_runner(calls):
    """The lock containers, faked: an export or a compile answers with a hash-locked file."""
    def run(args, stdin, timeout=900):
        calls.append((args, stdin))
        script = args[-1]
        tool = "uv export" if "uv export" in script else "uv pip compile"
        return f"# This file was autogenerated by uv via the following command:\n#    {tool} ...\nfastapi==0.115.0 \\\n    --hash=sha256:{'1' * 64}\n"
    return run


class AsIsGitHub(OnboardingGitHub):
    """The onboarding fake with sizes, larger reads, visibility and the release pull requests of Phase 13."""

    def __init__(self):
        super().__init__()
        self.repos["lab/asis"] = {"files": {"main.py": FASTAPI, "requirements.txt": "fastapi==0.115.0\n", "tests/test_main.py": "from main import app\n"},
                                  "default_branch": "main"}
        self.repos["lab/demo"] = {"files": {"platform.yaml": "name: demo\nreviewed: true\n"}, "default_branch": "main"}
        self.private = set()
        self.closed = []

    def set_environment_variables(self, repository, name, variables):
        self.variables.setdefault((repository, name), {}).update(variables)  # GitHub sets each variable; the others stay

    def repository(self, repository):
        info = super().repository(repository)
        return {**info, "full_name": repository, "private": repository in self.private}

    def tree(self, repository, ref, sizes=False):
        files = self.repos[repository]["files"]
        folders = {path.rsplit("/", 1)[0] for path in files if "/" in path}
        paths = sorted(set(files) | folders)
        return (paths, {path: len(text) for path, text in files.items()}) if sizes else paths

    def contents(self, repository, ref, path, limit=65_536):
        # At a pull request's head, the file as that pull request has it (the newest open one that changes it).
        for (repo, _), pr in sorted(self.prs.items(), key=lambda item: -item[0][1]):
            if repo == repository and ref == pr["head_sha"] and path in pr["files"] and not pr["merged"] and not pr.get("closed"):
                return {"sha": "s", "text": pr["files"][path]}
        return super().contents(repository, ref, path)

    def head(self, app):
        return self.sha

    def pull_request(self, repository, number):
        pr = self.prs[(repository, number)]
        state = "closed" if pr["merged"] or pr.get("closed") else "open"
        return {"number": number, "state": state, "merged": pr["merged"], "mergeable_state": pr["mergeable_state"], "head_sha": pr["head_sha"],
                "merge_commit_sha": "9" * 40 if pr["merged"] else None, "url": pr["url"], "merged_by": "brian" if pr["merged"] else None}

    def open_pull_requests(self, repository, prefix):
        return [{"number": number, "url": pr["url"], "branch": pr["branch"], "head_sha": pr["head_sha"]}
                for (repo, number), pr in self.prs.items() if repo == repository and pr["branch"].startswith(prefix) and not pr["merged"] and not pr.get("closed")]

    def close_pull_request(self, repository, number, comment):
        self.prs[(repository, number)]["closed"] = True
        self.closed.append(number)
        return {"number": number, "closed": True}


