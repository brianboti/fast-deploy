def test_the_reader_reads_compose_for_port_health_needs_and_command():
    compose = ("services:\n  api:\n    build: ./api\n    ports: ['8001:8000']\n    depends_on: [db]\n    environment:\n      DATABASE_URL: postgres://x\n"
               "    healthcheck:\n      test: ['CMD', 'curl', '-f', 'http://localhost:8000/ready']\n"
               "  web:\n    build: ./web\n    command: gunicorn -b 0.0.0.0:9000 main:app\n    ports: ['9000:9000']\n  db:\n    image: postgres:16\n")
    files = {"compose.yaml": compose, "api/Dockerfile": "FROM python:3.11-slim\nUSER 65532\nCMD [\"python\", \"main.py\"]\n", "api/main.py": "x = 1\n",
             "api/requirements.txt": "flask\n", "web/main.py": "from flask import Flask\napp = Flask(__name__)\n", "web/requirements.txt": "flask==3.0.0\n"}
    api = read(files, "api")["spec"]
    assert (api.port, api.health_path, api.python) == (8000, "/ready", "3.11")
    assert api.needs.database == "postgres" and api.needs.database_auth == "password"
    web = read(files, "web")["spec"]
    assert web.port == 9000 and web.build.recipe == "platform" and web.build.entrypoint == "gunicorn -b 0.0.0.0:9000 main:app"
    # A Compose command for a service with its own Dockerfile replaces the image's CMD at run time.
    files["compose.yaml"] = "services:\n  api:\n    build: ./api\n    command: gunicorn -b 0.0.0.0:8000 main:app\n    ports: ['8000:8000']\n"
    assert read(files, "api")["spec"].args == ["gunicorn", "-b", "0.0.0.0:8000", "main:app"]
    # Two services built from one folder: the one that publishes a port is the web service; otherwise it is refused.
    files["compose.yaml"] = "services:\n  api:\n    build: ./api\n    ports: ['8000:8000']\n  worker:\n    build: ./api\n    command: celery -A main worker\n"
    assert read(files, "api")["spec"].port == 8000
    files["compose.yaml"] = "services:\n  api:\n    build: ./api\n  worker:\n    build: ./api\n"
    assert "several Compose services" in read(files, "api")["refusals"][0]["problem"]
    assert reader.services(sorted(files), files) == [{"path": "api", "from": "compose.yaml, service api"}]


