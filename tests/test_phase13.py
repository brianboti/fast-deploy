def test_the_lock_ladder_and_its_conversions():
    lock = "fastapi==0.115.0 \\\n    --hash=sha256:" + "1" * 64 + "\n"
    served = lock + "uvicorn==0.30.0 \\\n    --hash=sha256:" + "5" * 64 + "\n"
    first = read({"requirements.lock": served, "requirements.txt": "fastapi\n", "uv.lock": "x", "pyproject.toml": "[project]\nname='x'\n", "main.py": FASTAPI})
    assert first["lock"]["action"] == "use" and {item["file"] for item in first["ignored"]} >= {"requirements.txt", "uv.lock"}
    # The server that starts it is missing from the repository's lock: the lock is compiled again with it, its pins kept.
    added = read({"requirements.lock": lock, "main.py": FASTAPI})["lock"]
    assert added["action"] == "compile" and added["input"] == "fastapi==0.115.0\n" and added["server"].startswith("uvicorn==")
    assert read({"uv.lock": "x", "pyproject.toml": "[project]\nname='x'\n", "requirements.txt": "fastapi\n", "main.py": FASTAPI})["lock"]["action"] == "export"
    poetry = ("[[package]]\nname = 'fastapi'\nversion = '0.115.0'\ngroups = ['main']\nmarkers = \"python_version >= '3.8'\"\n"
              f"files = [{{file = 'f.whl', hash = 'sha256:{'2' * 64}'}}]\n"
              "[[package]]\nname = 'pytest'\nversion = '8.0.0'\ngroups = ['dev']\nfiles = []\n")
    text, problems = reader.poetry_lock_requirements(poetry)
    assert not problems and "fastapi==0.115.0 ; python_version >= '3.8'" in text and "pytest" not in text and "2" * 64 in text
    _, problems = reader.poetry_lock_requirements("[[package]]\nname = 'mine'\nversion = '1'\nsource = {type = 'directory', url = '../mine'}\n")
    assert problems == ["mine comes from a directory source"]
    pipfile = json.dumps({"default": {"flask": {"version": "==3.0.0", "hashes": ["sha256:" + "3" * 64]}, "local": {"path": "."}}})
    text, problems = reader.pipfile_lock_requirements(pipfile)
    assert "flask==3.0.0" in text and problems and "local" in problems[0]
    assert reader.pins_of(lock + "uvicorn==0.30.0 ; sys_platform != 'win32' \\\n    --hash=sha256:" + "4" * 64 + "\n") == [
        "fastapi==0.115.0", "uvicorn==0.30.0 ; sys_platform != 'win32'"]


